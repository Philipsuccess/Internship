from typing import List, Literal, Optional
from pydantic import BaseModel, Field, ConfigDict, field_validator

class HistoryMessage(BaseModel):
    """A message in the prior conversation history.
    
    Supports extra metadata (id, timestamp, token_count) with extra='ignore'
    to maintain seamless compatibility with frontend client models and future DB schemas.
    """
    role: str = Field(
        ..., 
        description="Role of the message sender, e.g. 'user', 'assistant', or 'model'"
    )
    content: str = Field(
        ..., 
        min_length=1, 
        max_length=10000,
        description="Text content of the message (up to 10,000 characters)"
    )

    model_config = ConfigDict(extra="ignore")

    @field_validator("role")
    @classmethod
    def normalize_role(cls, v: str) -> str:
        role_lower = v.strip().lower()
        if role_lower in ("assistant", "model", "ai", "bot"):
            return "model"
        if role_lower in ("user", "human"):
            return "user"
        raise ValueError(
            f"Invalid role '{v}'. Supported roles are 'user' or 'assistant' ('model')."
        )

class ChatRequest(BaseModel):
    """Payload schema for POST /api/chat.
    
    Includes session_id for future database persistence integration,
    and optional persona selection for specialized AI behaviors.
    """
    message: str = Field(
        ..., 
        min_length=1, 
        max_length=10000,
        description="The current user message (up to 10,000 characters)"
    )
    conversation_history: List[HistoryMessage] = Field(
        default_factory=list,
        max_length=50,
        description="List of prior conversation messages (up to 50 turns)"
    )
    session_id: Optional[str] = Field(
        default=None,
        max_length=128,
        description="Optional session or conversation ID for future database persistence"
    )
    persona: Optional[str] = Field(
        default=None,
        max_length=50,
        description="Optional persona identifier (e.g. 'student_tutor', 'coding_assistant')"
    )

    model_config = ConfigDict(extra="ignore")

    @field_validator("message")
    @classmethod
    def validate_message_not_empty(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Message cannot be empty or whitespace-only")
        if len(trimmed) > 10000:
            raise ValueError("Message exceeds maximum allowed limit of 10,000 characters")
        return trimmed

class ChatResponse(BaseModel):
    """Successful response schema for POST /api/chat."""
    response: str = Field(
        ..., 
        description="AI response generated by Gemini"
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Session identifier associated with this conversation"
    )

class ErrorDetailResponse(BaseModel):
    """Standardized error response schema."""
    detail: str = Field(..., description="User-friendly error explanation")
